"""The decision frame: the one structured representation every ADAPT component shares.

Free text, structured input, retrieved evidence and model outputs all converge on a
DecisionFrame. Domain generality lives here, in the schema, not in any model: a
career choice and a laptop purchase are both options scored against criteria under
constraints.

Every value carries its provenance so the system never confuses what the user said
with what it assumed, inferred, looked up, or calculated.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Union

from pydantic import BaseModel, Field, HttpUrl, model_validator

SCHEMA_VERSION = "0.1.0"

Scalar = Union[bool, int, float, str]


class Provenance(str, Enum):
    STATED = "stated"  # the user said it
    ASSUMED = "assumed"  # the system filled a gap; must be surfaced to the user
    INFERRED = "inferred"  # a model extracted or predicted it
    RETRIEVED = "retrieved"  # came from an external source; requires a Source
    COMPUTED = "computed"  # deterministic calculation from other values


class Source(BaseModel):
    url: HttpUrl
    title: str | None = None
    published_at: datetime | None = None
    retrieved_at: datetime


class Value(BaseModel):
    value: Scalar
    unit: str | None = None
    provenance: Provenance
    source: Source | None = None

    @model_validator(mode="after")
    def _retrieved_needs_source(self) -> Value:
        if self.provenance is Provenance.RETRIEVED and self.source is None:
            raise ValueError("retrieved values must cite a source")
        return self


class Direction(str, Enum):
    MAXIMIZE = "maximize"
    MINIMIZE = "minimize"


class Criterion(BaseModel):
    """A soft preference: something to trade off, not something that must hold."""

    attribute: str
    direction: Direction
    # None means the user has not told us how much this matters. That is a
    # clarification target, not something to silently default.
    weight: float | None = Field(default=None, ge=0)
    provenance: Provenance = Provenance.STATED


class Operator(str, Enum):
    LE = "<="
    GE = ">="
    LT = "<"
    GT = ">"
    EQ = "=="
    NE = "!="


class Constraint(BaseModel):
    """A hard limit. Options that violate it are excluded, whatever their score."""

    attribute: str
    operator: Operator
    value: Scalar
    unit: str | None = None
    provenance: Provenance = Provenance.STATED


class Option(BaseModel):
    id: str = Field(min_length=1)
    label: str
    attributes: dict[str, Value] = Field(default_factory=dict)
    provenance: Provenance = Provenance.STATED  # was it given, or generated by ADAPT?


class DecisionFrame(BaseModel):
    schema_version: str = SCHEMA_VERSION
    situation: str
    domain_hint: str | None = None
    goals: list[str] = Field(default_factory=list)
    options: list[Option] = Field(default_factory=list)
    criteria: list[Criterion] = Field(default_factory=list)
    constraints: list[Constraint] = Field(default_factory=list)
    context: dict[str, Value] = Field(default_factory=dict)  # facts not tied to one option
    unknowns: list[str] = Field(default_factory=list)  # open questions known to matter

    @model_validator(mode="after")
    def _unique_ids(self) -> DecisionFrame:
        ids = [o.id for o in self.options]
        if len(ids) != len(set(ids)):
            raise ValueError("option ids must be unique")
        attrs = [c.attribute for c in self.criteria]
        if len(attrs) != len(set(attrs)):
            raise ValueError("each attribute may appear in at most one criterion")
        return self

    def missing_attributes(self) -> list[tuple[str, str]]:
        """(option_id, attribute) pairs that a criterion or constraint needs but the option lacks."""
        needed = {c.attribute for c in self.criteria} | {c.attribute for c in self.constraints}
        return [
            (o.id, a) for o in self.options for a in sorted(needed) if a not in o.attributes
        ]

    def unweighted_criteria(self) -> list[str]:
        return [c.attribute for c in self.criteria if c.weight is None]

    def assumptions(self) -> list[str]:
        """Human-readable list of every assumed value, so none can be hidden from the user."""
        out = [f"context.{k}" for k, v in self.context.items() if v.provenance is Provenance.ASSUMED]
        for o in self.options:
            out += [
                f"{o.id}.{k}" for k, v in o.attributes.items() if v.provenance is Provenance.ASSUMED
            ]
        return out
